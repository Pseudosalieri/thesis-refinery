"""The cover document, imported at the top of the body, byte for byte.

Ported from the private pipeline this project was extracted from, and the *reason*
it works the way it does is the most important thing this module carries.

**An earlier version of that pipeline destroyed a cover page.** It rewrote a
page-count field, which rebuilt the paragraph from the first run's formatting: the
run lost its ``w:hint="eastAsia"`` attribute, and a hand-filled placeholder became
an empty field result, so the page printed blank. The author's verdict was that the
cover outranks every check in the project, and the pipeline was changed to import the
cover pages and never touch a character of them.

So the rule this stage follows is: **deep-copy the source's body nodes and never
rebuild a paragraph from its text.** No field is introduced, no placeholder is
filled, no text is replaced. What that costs is stated rather than hidden — a
placeholder stays a placeholder, and the author fills it in Word — and what it buys
is that the cover is the one part of the document this tool cannot corrupt.

Three things do have to be translated, because a relationship id and a style id are
only meaningful in the part that declares them:

* **Styles** are copied with an ``FM_`` prefix and their ``basedOn``/``next``/``link``
  dependencies, so an imported paragraph keeps its appearance without colliding with
  a style of the same id in the target — which would silently change the body.
* **Relationships** are copied and their ids remapped; media is de-duplicated by
  content hash, and a source part the target already holds is shared rather than
  copied.
* **Drawing ids** are renumbered, because ``wp:docPr/@id`` must be unique in the
  document and a collision is a repair prompt in Word.
"""

from __future__ import annotations

import hashlib
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

from lxml import etree

from thesis_refinery.config import ConfigError
from thesis_refinery.docxlib.ns import q, qn
from thesis_refinery.docxlib.pkgs import Package
from thesis_refinery.docxlib.xmlq import (
    Element,
    children,
    deepcopy,
    find,
    iter_descendants,
    new,
    ordered_insert,
    text_of,
)
from thesis_refinery.style import StyleSpec

__all__ = ["DOCUMENT_PART", "OptionsError", "apply"]

DOCUMENT_PART = "word/document.xml"
STYLES_PART = "word/styles.xml"
RELS_PART = "word/_rels/document.xml.rels"

STYLE_ID_PREFIX = "FM_"
"""Prefix for every imported style id.

Not decoration: the imported cover's styles and the body's share names, and a cover
whose ``Normal`` overwrote the body's would restyle the thesis.
"""

_RELATIONSHIP_ATTRIBUTES = (qn("r:id"), qn("r:embed"), qn("r:link"))
_STYLE_REFERENCES = ("w:pStyle", "w:rStyle", "w:tblStyle")
_STYLE_DEPENDENCIES = ("w:basedOn", "w:next", "w:link", "w:numStyleLink", "w:styleLink")
_DRAWING_IDS = (qn("wp:docPr"), qn("pic:cNvPr"))

_KNOWN_OPTIONS = frozenset({"source", "drop_title_style"})


class OptionsError(ConfigError):
    """Raised when the stage's ``options`` are missing or wrong."""


@dataclass(frozen=True)
class _Options:
    source: Path
    drop_title_style: str


def _read_options(raw: Mapping[str, object] | None) -> _Options:
    given = dict(raw or {})
    unknown = sorted(set(given) - _KNOWN_OPTIONS)
    if unknown:
        raise OptionsError(
            f"unknown option(s) for the front-matter stage: {', '.join(unknown)}.\n"
            f"Known: {', '.join(sorted(_KNOWN_OPTIONS))}"
        )

    if "source" not in given:
        raise OptionsError(
            "the front-matter stage needs a cover document.\n"
            "Set `frontmatter_docx` at the top level of thesis.yml to a .docx whose "
            "leading pages are the cover, or remove the setting to leave the stage out."
        )

    return _Options(
        source=Path(str(given["source"])),
        drop_title_style=str(given.get("drop_title_style", "Title")),
    )


# ---------------------------------------------------------------------------
# Reading the source cover
# ---------------------------------------------------------------------------


def _front_nodes(source_body: Element, *, has_toc: bool) -> list[Element]:
    """The cover's body nodes: everything before the first section boundary.

    Three boundaries, because a cover document arrives in more than one shape:

    * a **body-level ``w:sectPr``** with no table of contents — the shape a
      *prepared* cover has, already trimmed to the pages that belong to it;
    * a **table of contents** in an ``w:sdt``, which is regenerated by the renderer
      and must not be imported as if it were part of the cover;
    * a **paragraph-level ``w:sectPr``**, which ends the cover's section.

    A scan with no boundary runs to the end of the source and imports the whole
    document as a cover.
    """
    nodes: list[Element] = []
    body_children = [child for child in children(source_body) if isinstance(child.tag, str)]

    for index, element in enumerate(body_children):
        if element.tag == q("sectPr"):
            if not has_toc:
                return [deepcopy(child) for child in body_children[:index]]
            break
        if element.tag == q("sdt"):
            break
        if element.tag == q("p"):
            properties = find(element, "w:pPr")
            if properties is not None and find(properties, "w:sectPr") is not None:
                nodes.append(deepcopy(element))
                break
        nodes.append(deepcopy(element))
    else:
        return nodes

    if not nodes:
        raise OptionsError(
            "the cover document's first body child is a section boundary or a table "
            "of contents, so it has no cover pages to import"
        )
    return nodes


def _has_toc(source_body: Element) -> bool:
    return any(child.tag == q("sdt") for child in children(source_body))


# ---------------------------------------------------------------------------
# Styles
# ---------------------------------------------------------------------------


def _used_style_ids(nodes: Sequence[Element]) -> set[str]:
    used: set[str] = set()
    for element in nodes:
        for node in element.iter():
            if node.tag not in {q(tag.removeprefix("w:")) for tag in _STYLE_REFERENCES}:
                continue
            value = node.get(qn("w:val"))
            if value:
                used.add(value)
    return used


def _style_index(styles_root: Element | None) -> dict[str, Element]:
    if styles_root is None:
        return {}
    return {
        style.get(qn("w:styleId")): style
        for style in iter_descendants(styles_root, "w:style")
        if style.get(qn("w:styleId"))
    }


def _merge_front_styles(
    target_styles: Element | None, source_styles: Element | None, nodes: Sequence[Element]
) -> dict[str, str]:
    """Copy the styles the cover uses, renamed, and rewrite the cover's references.

    The dependency closure matters: a style copied without the style it is
    ``basedOn`` inherits from ``Normal`` instead, and the cover's appearance changes
    without anything in the file saying so.
    """
    used = _used_style_ids(nodes)
    index = _style_index(source_styles)

    pending = list(used)
    while pending:
        style = index.get(pending.pop())
        if style is None:
            continue
        for tag in _STYLE_DEPENDENCIES:
            dependency = find(style, tag)
            value = dependency.get(qn("w:val")) if dependency is not None else None
            if value and value not in used:
                used.add(value)
                pending.append(value)

    mapping = {style_id: f"{STYLE_ID_PREFIX}{style_id}" for style_id in used}

    for element in nodes:
        for node in element.iter():
            if node.tag not in {q(tag.removeprefix("w:")) for tag in _STYLE_REFERENCES}:
                continue
            value = node.get(qn("w:val"))
            if value in mapping:
                node.set(qn("w:val"), mapping[value])

    if target_styles is None:
        return mapping

    for style_id in sorted(used):
        source_style = index.get(style_id)
        if source_style is None:
            continue
        style = deepcopy(source_style)
        style.set(qn("w:styleId"), mapping[style_id])
        for tag in _STYLE_DEPENDENCIES:
            dependency = find(style, tag)
            if dependency is None:
                continue
            value = dependency.get(qn("w:val"))
            if value in mapping:
                dependency.set(qn("w:val"), mapping[value])
        target_styles.append(style)
    return mapping


# ---------------------------------------------------------------------------
# Relationships and media
# ---------------------------------------------------------------------------


def _referenced_relationship_ids(nodes: Sequence[Element]) -> set[str]:
    ids: set[str] = set()
    for element in nodes:
        for node in element.iter():
            for attribute, value in node.attrib.items():
                if attribute in _RELATIONSHIP_ATTRIBUTES:
                    ids.add(value)
    return ids


def _next_relationship_id(existing: set[str]) -> str:
    """An id no part of the target uses.

    A fixed prefix rather than a number, so an imported relationship is
    recognisable in a document that has been through this stage.
    """
    index = 1
    while f"fmRId{index}" in existing:
        index += 1
    return f"fmRId{index}"


def _copy_relationships(
    package: Package,
    source: Package,
    nodes: Sequence[Element],
    target_rels: Element,
) -> None:
    """Copy the relationships the cover uses, remapping ids and de-duplicating media.

    Media is matched by content hash, not by name. Two covers that embed the same
    logo store it under different names, and copying it twice would double the size
    of every build's output for nothing.
    """
    wanted = _referenced_relationship_ids(nodes)
    source_rels = {rel.get("Id"): rel for rel in source.relationships(DOCUMENT_PART)}
    existing = {rel.get("Id") for rel in target_rels}

    digests = {
        hashlib.sha256(package.read(name)).hexdigest(): name
        for name in package.names()
        if name.startswith("word/media/")
    }

    remap: dict[str, str] = {}
    for source_id in sorted(wanted):
        relation = source_rels.get(source_id)
        if relation is None:
            raise OptionsError(
                f"the cover references relationship {source_id!r}, which its document "
                "part does not declare"
            )

        new_id = _next_relationship_id(existing)
        existing.add(new_id)
        copy = deepcopy(relation)
        copy.set("Id", new_id)

        mode = relation.get("TargetMode")
        target = relation.get("Target") or ""
        kind = (relation.get("Type") or "").rsplit("/", 1)[-1]

        if mode == "External":
            pass
        elif kind == "image":
            name = f"word/{target}"
            if not source.exists(name):
                raise OptionsError(f"the cover's image part {name} is missing")
            data = source.read(name)
            digest = hashlib.sha256(data).hexdigest()
            reused = digests.get(digest)
            if reused is None:
                reused = _free_media_name(package, target)
                package.write(reused, data)
                digests[digest] = reused
            copy.set("Target", reused.removeprefix("word/"))
        else:
            raise OptionsError(
                f"the cover's relationship {source_id!r} points at {target!r} "
                f"({kind or 'no type'}), which this stage cannot carry across.\n"
                "Only images and external targets are supported; a cover that embeds "
                "an object needs that object handled deliberately, not guessed at."
            )

        target_rels.append(copy)
        remap[source_id] = new_id

    for element in nodes:
        for node in element.iter():
            for attribute, value in list(node.attrib.items()):
                if attribute in _RELATIONSHIP_ATTRIBUTES and value in remap:
                    node.set(attribute, remap[value])


def _free_media_name(package: Package, target: str) -> str:
    base = Path(target).name
    candidate = f"word/media/frontmatter_{base}"
    suffix = 1
    while package.exists(candidate):
        candidate = f"word/media/frontmatter_{suffix}_{base}"
        suffix += 1
    return candidate


def _remap_drawing_ids(nodes: Sequence[Element], target_root: Element) -> None:
    """Renumber ``wp:docPr``/``pic:cNvPr`` so no id repeats.

    Word treats a duplicate drawing id as a corrupt document and offers to repair
    it, which is a worse outcome than the cover looking slightly different.
    """
    highest = 0
    for element in target_root.iter():
        if element.tag not in _DRAWING_IDS:
            continue
        try:
            highest = max(highest, int(element.get("id", "0")))
        except ValueError:
            continue

    for element in nodes:
        for drawing in element.iter():
            if drawing.tag not in _DRAWING_IDS:
                continue
            highest += 1
            drawing.set("id", str(highest))


