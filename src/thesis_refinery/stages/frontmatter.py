def _refuse_if_already_imported(body: Element, nodes: Sequence[Element]) -> None:
    """Refuse a document whose body already begins with the cover pages.

    There is no marker element to look for, deliberately: a marker would be one more
    thing this stage writes into pages it promises not to touch. The leading
    paragraphs' text is compared instead.

    The failure this prevents is the one that would otherwise be silent — a build
    pointed at an already-assembled document imports the cover a second time, and
    the result opens with two covers and no complaint from anything.
    """
    cover_text = [text_of(paragraph) for paragraph in nodes if paragraph.tag == q("p")]
    if not cover_text:
        return

    leading = [
        text_of(paragraph) for paragraph in children(body) if paragraph.tag == q("p")
    ][: len(cover_text)]
    if leading == cover_text:
        raise OptionsError(
            "this document's body already begins with the cover pages, so importing "
            "them again would give it two covers.\n"
            "Point `frontmatter_docx` at a cover, not at an assembled thesis."
        )


def apply(
    source: Path,
    destination: Path,
    *,
    style: StyleSpec,
    options: Mapping[str, object] | None = None,
) -> Path:
    """Read *source*, import the cover at the top of its body, write *destination*.

    *source* is the rendered thesis; ``options["source"]`` is the cover document.
    Neither is modified: :meth:`Package.save` refuses a destination that is its own
    input, and this stage relies on that refusal for the rendered document.
    """
    settings = _read_options(options)
    source = Path(source)
    destination = Path(destination)

    if not settings.source.exists():
        raise OptionsError(
            f"the cover document {settings.source} does not exist.\n"
            "Set `frontmatter_docx` in thesis.yml, or remove it to leave this stage out."
        )
    if settings.source.resolve() == source.resolve():
        raise OptionsError("the cover document and the rendered document are the same file")

    with Package(source) as package, Package(settings.source) as cover:
        document = package.xml(DOCUMENT_PART)
        before = etree.tostring(document)

        body = find(document, "w:body")
        if body is None:
            raise OptionsError(f"{source} has no w:body in {DOCUMENT_PART}")

        cover_document = cover.xml(DOCUMENT_PART)
        cover_body = find(cover_document, "w:body")
        if cover_body is None:
            raise OptionsError(f"{settings.source} has no w:body in {DOCUMENT_PART}")

        nodes = _front_nodes(cover_body, has_toc=_has_toc(cover_body))

        source_section = find(cover_body, "w:sectPr")
        if source_section is None:
            found = [
                section
                for paragraph in iter_descendants(cover_body, "w:p")
                if (properties := find(paragraph, "w:pPr")) is not None
                and (section := find(properties, "w:sectPr")) is not None
            ]
            source_section = found[-1] if found else None
        break_node = _section_break_node(source_section, style)

        styles_root = package.xml(STYLES_PART) if package.exists(STYLES_PART) else None
        styles_before = etree.tostring(styles_root) if styles_root is not None else None
        cover_styles = cover.xml(STYLES_PART) if cover.exists(STYLES_PART) else None
        _merge_front_styles(styles_root, cover_styles, nodes)

        rels = package.xml(RELS_PART)
        rels_before = etree.tostring(rels)
        _copy_relationships(package, cover, nodes, rels)

        _remap_drawing_ids(nodes, document)

        names = {
            style_element.get(qn("w:styleId"), ""): (
                find(style_element, "w:name").get(qn("w:val"), "")
                if find(style_element, "w:name") is not None
                else ""
            )
            for style_element in iter_descendants(styles_root, "w:style")
        } if styles_root is not None else {}
        _drop_generated_title(body, settings.drop_title_style, names)

        _refuse_if_already_imported(body, nodes)

        for element in reversed([*nodes, break_node]):
            body.insert(0, element)

        if etree.tostring(document) != before:
            package.replace_xml(DOCUMENT_PART, document)
        if etree.tostring(rels) != rels_before:
            package.replace_xml(RELS_PART, rels)
        if (
            styles_root is not None
            and styles_before is not None
            and etree.tostring(styles_root) != styles_before
        ):
            package.replace_xml(STYLES_PART, styles_root)

        return package.save(destination)
