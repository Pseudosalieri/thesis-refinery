# The section the cover lives in
# ---------------------------------------------------------------------------


def _section_break_node(source_section: Element | None, style: StyleSpec) -> Element:
    """A paragraph carrying the section properties the cover pages are laid out with.

    The source's own properties when it has them: the cover's page size and margins
    are a fact about that document, and re-deciding them from the specification would
    reflow a page the author has looked at. The specification is the fallback for a
    cover that declares no section of its own, and the fallback is stated in the
    docstring rather than hidden — it is a guess, and a cover built from it may need
    its margins adjusting.
    """
    paragraph = new("w:p")
    properties = ordered_insert(paragraph, new("w:pPr"))

    if source_section is not None:
        ordered_insert(properties, deepcopy(source_section))
        return paragraph

    section = ordered_insert(properties, new("w:sectPr"))
    margins = style.margins
    size = ordered_insert(section, new("w:pgSz"))
    size.set(qn("w:w"), str(style.page.width_twips))
    size.set(qn("w:h"), str(style.page.height_twips))
    page_margins = ordered_insert(section, new("w:pgMar"))
    side = margins.front_matter_side_twips
    for attribute, value in (
        ("top", margins.top_twips),
        ("bottom", margins.bottom_twips),
        ("left", side),
        ("right", side),
        ("header", margins.header_distance_twips),
        ("footer", margins.footer_distance_twips),
    ):
        page_margins.set(qn(f"w:{attribute}"), str(value))
    return paragraph


def _drop_generated_title(body: Element, style_name: str, names: Mapping[str, str]) -> int:
    """Remove the title the renderer generated from the project's metadata.

    That title page exists so a document *without* a cover still says what it is. With
    a cover imported, it is a second title page — and the one the author did not
    write. Only leading paragraphs are removed, and only while they carry the title
    style, so a later paragraph that happens to use it is left alone.
    """
    if not style_name:
        return 0

    removed = 0
    for child in list(children(body)):
        if child.tag != q("p"):
            break
        properties = find(child, "w:pPr")
        identifier = ""
        if properties is not None:
            style = find(properties, "w:pStyle")
            if style is not None:
                identifier = style.get(qn("w:val")) or ""
        if names.get(identifier, identifier) != style_name:
            break
        body.remove(child)
        removed += 1
    return removed


